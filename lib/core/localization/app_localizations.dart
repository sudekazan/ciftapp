  }

  /// [text] with `{name}` placeholders replaced, e.g. `textf('k', {'n': 3})`.
  String textf(String key, Map<String, Object> args) {
    var value = text(key);
    args.forEach((name, arg) => value = value.replaceAll('{$name}', '$arg'));
    return value;
  }
